// Regenerates public/sitemap.xml from the route table (indexable routes only).
// Usage: npm run sitemap    (Node >= 22.18 runs this TypeScript directly)
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROUTES } from "../src/app/routes/routeTable.ts";

const ORIGIN = "https://paperwarefactory.com";
const today = new Date().toISOString().slice(0, 10);
const urls = ROUTES.filter((r) => !r.noindex)
  .map((r) => `  <url>\n    <loc>${ORIGIN}${r.path}</loc>\n    <lastmod>${today}</lastmod>\n  </url>`)
  .join("\n");
const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/generate-sitemap.ts from src/app/routes/routeTable.ts. Do not edit by hand. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
writeFileSync(join(import.meta.dirname, "..", "public", "sitemap.xml"), xml);
console.log(`sitemap.xml: ${ROUTES.filter((r) => !r.noindex).length} URLs`);
